source_cam_log = np.log(np.clip(source_cam, 1e-8, 1.0))
source_aud_log = np.log(np.clip(source_aud, 1e-8, 1.0))
target_cam_log = np.log(np.clip(camera_target, 1e-8, 1.0))
target_aud_log = np.log(np.clip(audio_target, 1e-8, 1.0))

best_alpha = 0.5
