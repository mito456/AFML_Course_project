def evaluate_policy_detailed(defer_mask, fusion_preds, vis_preds, y_true, site_array):
    final_preds = np.where(defer_mask, fusion_preds, vis_preds)
    macro_f1 = f1_score(y_true, final_preds, average="macro", labels=range(n_classes), zero_division=0)
    acc = accuracy_score(y_true, final_preds)
    act_rate = np.mean(defer_mask)

    unique_sites = np.unique(site_array)
    boot_f1s = []
    rng = np.random.default_rng(CONFIG["bootstrap_seed"])
    for _ in range(CONFIG["bootstrap_draws"]):
        sampled_sites = rng.choice(unique_sites, size=len(unique_sites), replace=True)
        sampled_indices = np.concatenate([np.where(site_array == s)[0] for s in sampled_sites])
        if len(sampled_indices) > 0:
            boot_f1s.append(f1_score(y_true[sampled_indices], final_preds[sampled_indices], average="macro", labels=range(n_classes), zero_division=0))

    ci_low, ci_high = np.percentile(boot_f1s, [2.5, 97.5]) if boot_f1s else (macro_f1, macro_f1)
    return macro_f1, acc, act_rate, f"[{ci_low:.3f}, {ci_high:.3f}]"

def evaluate_paired_diff_bootstrap(final_preds_policy, final_preds_baseline, y_true, site_array):
    point_diff = f1_score(y_true, final_preds_policy, average="macro", labels=range(n_classes), zero_division=0) - f1_score(y_true, final_preds_baseline, average="macro", labels=range(n_classes), zero_division=0)
    unique_sites = np.unique(site_array)
    boot_diffs = []
    rng = np.random.default_rng(CONFIG["bootstrap_seed"])
    for _ in range(CONFIG["bootstrap_draws"]):
        sampled_sites = rng.choice(unique_sites, size=len(unique_sites), replace=True)
        sampled_indices = np.concatenate([np.where(site_array == s)[0] for s in sampled_sites])
        if len(sampled_indices) > 0:
            f1_p = f1_score(y_true[sampled_indices], final_preds_policy[sampled_indices], average="macro", labels=range(n_classes), zero_division=0)
            f1_b = f1_score(y_true[sampled_indices], final_preds_baseline[sampled_indices], average="macro", labels=range(n_classes), zero_division=0)
            boot_diffs.append(f1_p - f1_b)
    ci_low, ci_high = np.percentile(boot_diffs, [2.5, 97.5]) if boot_diffs else (point_diff, point_diff)
    return point_diff, f"[{ci_low:.3f}, {ci_high:.3f}]"

f1_vis, acc_vis, act_vis, ci_vis = evaluate_policy_detailed(np.zeros(len(y_true), dtype=bool), fusion_preds, vis_preds_base, y_true, site_ids)
