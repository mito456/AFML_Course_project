known_placements = sorted(source_oof_df["placement"].dropna().unique()) if "placement" in source_oof_df.columns else ["arboreal", "terrestrial", "unknown"]
def extract_pre_audio_features(cam_p_matrix, df_subset, known_placements):
    feats = []
    for i, (idx, row) in enumerate(df_subset.iterrows()):
        cp = cam_p_matrix[i]
        ordered = sorted(cp, reverse=True)
        entropy = -sum(q * np.log(max(q, 1e-8)) for q in cp)
        is_ir = float(row.get("is_ir", False) == True or row.get("is_ir") == "True")
        is_night = float(row.get("is_night", False) == True or row.get("is_night") == "True") if "is_night" in row else 0.0
        placement_feats = [float(row.get("placement") == val) for val in known_placements]
        feats.append(list(cp) + [entropy, ordered[0] - ordered[1], is_ir, is_night] + placement_feats)
    return np.array(feats)

source_target_oof = np.array([int(source_vis_preds[i] != source_y[i] and source_fusion_preds[i] == source_y[i]) for i in range(len(source_oof_df))])
