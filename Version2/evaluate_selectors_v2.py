for alpha in np.linspace(0.0, 1.0, 101):
    blend_log = alpha * source_cam_log + (1 - alpha) * source_aud_log
    macro_f1 = f1_score(source_y, np.argmax(blend_log, axis=1), average="macro", labels=range(n_classes), zero_division=0)
    if macro_f1 > best_f1:
        best_f1 = macro_f1
        best_alpha = alpha

p_fusion_log = best_alpha * target_cam_log + (1 - best_alpha) * target_aud_log
fusion_preds = np.argmax(p_fusion_log, axis=1)
vis_conf = np.max(camera_target, axis=1)
source_vis_conf = np.max(source_cam, axis=1)
source_vis_preds = np.argmax(source_cam, axis=1)
source_fusion_preds = np.argmax(best_alpha * source_cam_log + (1 - best_alpha) * source_aud_log, axis=1)

best_tau = 0.5
best_tau_f1 = -1.0
for tau in CONFIG["tau_grid"]:
    defer_source = source_vis_conf < tau
    f1 = f1_score(source_y, np.where(defer_source, source_fusion_preds, source_vis_preds), average="macro", labels=range(n_classes), zero_division=0)
    if f1 > best_tau_f1:
        best_tau_f1 = f1
